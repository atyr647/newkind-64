#!/usr/bin/env python3
"""
Convert a detailed ship model (for example one generated by Tripo) into an
N64-sized model for the Enhanced renderer.

  convert_ship_model.py <ship> <model.glb> [points] [faces]

<ship> names the original Elite ship the model stands in for (e.g. cobra3,
with its point table as the optional 3rd argument). The new model is turned
to face the same way as the original and scaled to the original's bounding
box, so it occupies exactly the same space in the game.

What it does:
  1. reduces the model to about <faces> triangles (default 500);
  2. makes it exactly left/right symmetric (the right half is mirrored),
     which halves the texture space needed;
  3. splits the surface into up to six "charts" by the direction it faces
     and gives each chart its own small texture (16 colours, at most
     64x64 - what fits in the N64's texture memory), filled from the
     detailed model's own texture;
  4. writes ships/<ship>.mesh.json and ships/<ship>_<n>.png.

Run tools/gen_ship_textures.py afterwards to regenerate n64_shiptex.c.

Needs: numpy, pillow, trimesh, scipy, rtree, shapely, fast-simplification.
"""
import json
import math
import os
import sys

import numpy as np
import trimesh
from PIL import Image
from scipy import ndimage

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ship_export import load_ship  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VERT_CACHE = 62          # vertices per batch (the RSP cache holds 70)
CREASE_DEGREES = 40.0    # edges sharper than this stay hard-edged


def load_reference(path):
    scene = trimesh.load(path, force="scene")
    meshes = [g for g in scene.dump() if isinstance(g, trimesh.Trimesh)]
    mesh = trimesh.util.concatenate(meshes) if len(meshes) > 1 else meshes[0]
    image = np.asarray(mesh.visual.material.baseColorTexture.convert("RGB"))
    return np.asarray(mesh.vertices, float), np.asarray(mesh.faces), np.asarray(mesh.visual.uv, float), image


def sample(image, uv):
    h, w, _ = image.shape
    x = np.clip((uv[:, 0] % 1.0) * (w - 1), 0, w - 1).astype(int)
    y = np.clip((1.0 - (uv[:, 1] % 1.0)) * (h - 1), 0, h - 1).astype(int)
    return image[y, x].astype(float)


def orient(verts, faces, uv, image, target_lo, target_hi):
    """
    Turn and scale the model into the original ship's frame: x = right,
    y = up, z = forwards. The model is assumed to be y-up. Its fore-aft
    axis is the horizontal axis with the reddest end (the engines), and
    that end is the rear.

    Thin protrusions (aerials, probes) are ignored when measuring the model,
    so the hull itself fills the original ship's bounding box; whatever then
    sticks out of that box is trimmed off by the caller.
    """
    lo = np.percentile(verts, 1.5, axis=0)
    hi = np.percentile(verts, 98.5, axis=0)
    ext = hi - lo

    centres = verts[faces].mean(axis=1)
    colours = sample(image, uv[faces].mean(axis=1))
    redness = colours[:, 0] - (colours[:, 1] + colours[:, 2]) / 2

    best = None
    for axis in (0, 2):
        t = (centres[:, axis] - (lo[axis] + hi[axis]) / 2) / (ext[axis] / 2)
        for sgn in (1, -1):
            end = (t * sgn > 0.6) & (t * sgn < 1.1)
            score = redness[end].mean() if end.any() else -1e9
            if best is None or score > best[0]:
                best = (score, axis, sgn)
    _, fwd, rear_sign = best
    side = 2 if fwd == 0 else 0

    def norm(a):
        return (verts[:, a] - (lo[a] + hi[a]) / 2) / (ext[a] / 2)

    out = np.zeros_like(verts)
    mid, half = (target_lo + target_hi) / 2, (target_hi - target_lo) / 2
    out[:, 0] = norm(side) * half[0]
    out[:, 1] = mid[1] + norm(1) * half[1]
    out[:, 2] = mid[2] - rear_sign * norm(fwd) * half[2]
    flipped = (np.linalg.det(np.array([[1 if i == side else 0 for i in range(3)],
                                       [0, 1, 0],
                                       [-rear_sign if i == fwd else 0 for i in range(3)]])) < 0)
    return out, flipped


def texture_size(w, h, area_share):
    """Pick a texture size (powers of two, <= 64x64) for a chart."""
    big = 64 if area_share > 0.08 else (32 if area_share > 0.01 else 16)
    aspect = w / h
    if aspect > 1.8:
        return big, max(big // 2, 8)
    if aspect < 0.55:
        return max(big // 2, 8), big
    return big, big


def main():
    ship, glb = sys.argv[1], sys.argv[2]
    point_name = sys.argv[3] if len(sys.argv) > 3 else ship + "_point"
    target_faces = int(sys.argv[4]) if len(sys.argv) > 4 else 500

    points, _ = load_ship(ship + "_face", point_name)
    opts = np.array(points, float)
    t_lo, t_hi = opts.min(axis=0), opts.max(axis=0)

    rv, rf, ruv, rimg = load_reference(glb)
    rv, flipped = orient(rv, rf, ruv, rimg, t_lo, t_hi)
    if flipped:
        rf = rf[:, ::-1]
    ref = trimesh.Trimesh(rv, rf, process=False)

    # --- 1. reduce -----------------------------------------------------------
    geo = trimesh.Trimesh(rv, rf, process=False)
    geo.merge_vertices(merge_tex=True, merge_norm=True)
    low = geo.simplify_quadric_decimation(face_count=target_faces)

    # Trim anything that sticks out of the original ship's box (see orient).
    margin = (t_hi - t_lo) * 0.04
    box_lo = np.array([-(t_hi[0] - t_lo[0]) / 2, t_lo[1], t_lo[2]]) - margin
    box_hi = np.array([(t_hi[0] - t_lo[0]) / 2, t_hi[1], t_hi[2]]) + margin
    for ax in range(3):
        n = np.zeros(3)
        n[ax] = 1
        low = trimesh.intersections.slice_mesh_plane(low, plane_normal=n, plane_origin=box_lo)
        low = trimesh.intersections.slice_mesh_plane(low, plane_normal=-n, plane_origin=box_hi)

    # --- 2. keep the right half; it will be mirrored -------------------------
    half = trimesh.intersections.slice_mesh_plane(low, plane_normal=[1, 0, 0], plane_origin=[0, 0, 0])
    half.merge_vertices()
    hv, hf = np.asarray(half.vertices, float), np.asarray(half.faces)
    hv[np.abs(hv[:, 0]) < 1e-6, 0] = 0.0
    tri = hv[hf]
    fn = np.cross(tri[:, 1] - tri[:, 0], tri[:, 2] - tri[:, 0])
    area = np.linalg.norm(fn, axis=1)
    keep = area > 1e-6
    hf, fn, area = hf[keep], fn[keep], area[keep]
    fn = fn / area[:, None]
    area = area / 2

    # --- smooth normals, but keep hard edges hard -----------------------------
    vert_faces = [[] for _ in range(len(hv))]
    for i, f in enumerate(hf):
        for v in f:
            vert_faces[v].append(i)
    cos_crease = math.cos(math.radians(CREASE_DEGREES))
    corner_normal = np.zeros((len(hf), 3, 3))
    for i, f in enumerate(hf):
        for k, v in enumerate(f):
            n = np.zeros(3)
            for j in vert_faces[v]:
                if fn[j] @ fn[i] >= cos_crease:
                    n += fn[j] * area[j]
            if v is not None and abs(hv[v][0]) < 1e-6:
                n[0] = 0.0                      # on the mirror plane
            ln = np.linalg.norm(n)
            corner_normal[i, k] = n / ln if ln > 1e-9 else fn[i]

    # --- 3. charts -------------------------------------------------------------
    axis = np.argmax(np.abs(fn), axis=1)
    sign = np.where(fn[np.arange(len(fn)), axis] >= 0, 1, -1)
    keys = sorted(set(zip(axis.tolist(), sign.tolist())))
    total_area = area.sum()
    proj_axes = {0: (2, 1), 1: (0, 2), 2: (0, 1)}

    charts = []
    corner_uv = np.zeros((len(hf), 3, 2))
    face_chart = np.zeros(len(hf), int)
    for key in keys:
        sel = np.where((axis == key[0]) & (sign == key[1]))[0]
        a, b = proj_axes[key[0]]
        used = hv[hf[sel]].reshape(-1, 3)
        amin, amax = used[:, a].min(), used[:, a].max()
        bmin, bmax = used[:, b].min(), used[:, b].max()
        w, h = max(amax - amin, 1e-3), max(bmax - bmin, 1e-3)
        tw, th = texture_size(w, h, area[sel].sum() / total_area)
        # Leave half a texel of border so bilinear filtering stays inside.
        su, sv = (tw - 1.0) / w, (th - 1.0) / h
        cid = len(charts)
        face_chart[sel] = cid
        for i in sel:
            for k in range(3):
                p = hv[hf[i][k]]
                corner_uv[i, k] = (0.5 + (p[a] - amin) * su, 0.5 + (p[b] - bmin) * sv)

        # Bake: for every texel find the surface point, then the nearest
        # point of the detailed model, and take its colour.
        depth = np.full((th, tw), -1e30)
        pos = np.zeros((th, tw, 3))
        covered = np.zeros((th, tw), bool)
        for i in sel:
            uvs = corner_uv[i]
            x0, x1 = int(max(math.floor(uvs[:, 0].min() - 1), 0)), int(min(math.ceil(uvs[:, 0].max() + 1), tw - 1))
            y0, y1 = int(max(math.floor(uvs[:, 1].min() - 1), 0)), int(min(math.ceil(uvs[:, 1].max() + 1), th - 1))
            if x1 < x0 or y1 < y0:
                continue
            gy, gx = np.mgrid[y0:y1 + 1, x0:x1 + 1]
            px, py = gx + 0.5, gy + 0.5
            d = ((uvs[1, 1] - uvs[2, 1]) * (uvs[0, 0] - uvs[2, 0]) + (uvs[2, 0] - uvs[1, 0]) * (uvs[0, 1] - uvs[2, 1]))
            if abs(d) < 1e-9:
                continue
            l0 = ((uvs[1, 1] - uvs[2, 1]) * (px - uvs[2, 0]) + (uvs[2, 0] - uvs[1, 0]) * (py - uvs[2, 1])) / d
            l1 = ((uvs[2, 1] - uvs[0, 1]) * (px - uvs[2, 0]) + (uvs[0, 0] - uvs[2, 0]) * (py - uvs[2, 1])) / d
            l2 = 1 - l0 - l1
            inside = (l0 >= -0.35) & (l1 >= -0.35) & (l2 >= -0.35)
            p3 = (l0[..., None] * hv[hf[i][0]] + l1[..., None] * hv[hf[i][1]] + l2[..., None] * hv[hf[i][2]])
            dd = p3[..., key[0]] * key[1]
            better = inside & (dd > depth[y0:y1 + 1, x0:x1 + 1])
            depth[y0:y1 + 1, x0:x1 + 1][better] = dd[better]
            pos[y0:y1 + 1, x0:x1 + 1][better] = p3[better]
            covered[y0:y1 + 1, x0:x1 + 1] |= better

        tex = np.zeros((th, tw, 3))
        if covered.any():
            q = pos[covered]
            closest, _, tid = trimesh.proximity.closest_point(ref, q)
            bary = trimesh.triangles.points_to_barycentric(ref.triangles[tid], closest)
            uv = (ruv[rf[tid]] * bary[:, :, None]).sum(axis=1)
            tex[covered] = sample(rimg, uv)
            if not covered.all():
                idx = ndimage.distance_transform_edt(~covered, return_distances=False, return_indices=True)
                tex = tex[idx[0], idx[1]]
        name = "%s_%d" % (ship, cid)
        img = Image.fromarray(np.clip(tex, 0, 255).astype(np.uint8), "RGB")
        img.quantize(16, method=Image.MEDIANCUT, dither=Image.NONE).save(os.path.join(ROOT, "ships", name + ".png"))
        charts.append({"file": name, "w": tw, "h": th})

    # --- 4. mirror, and cut into batches that fit the vertex cache -------------
    tris = []      # (chart, [3 x (x, y, z, nx, ny, nz, u, v)])
    for i, f in enumerate(hf):
        corners = [tuple(hv[f[k]]) + tuple(corner_normal[i, k]) + tuple(corner_uv[i, k]) for k in range(3)]
        tris.append((int(face_chart[i]), corners))
        mirrored = [(-c[0], c[1], c[2], -c[3], c[4], c[5], c[6], c[7]) for c in corners]
        tris.append((int(face_chart[i]), mirrored[::-1]))
    tris.sort(key=lambda t: t[0])

    def pack(c):
        return (int(round(c[0])), int(round(c[1])), int(round(c[2])),
                int(round(c[3] * 127)), int(round(c[4] * 127)), int(round(c[5] * 127)),
                int(round(c[6] * 32)), int(round(c[7] * 32)))

    batches = []
    cur = None
    for chart, corners in tris:
        packed = [pack(c) for c in corners]
        new = [p for p in set(packed) if cur is None or p not in cur["index"]]
        if cur is None or cur["chart"] != chart or len(cur["verts"]) + len(new) > VERT_CACHE:
            cur = {"chart": chart, "verts": [], "tris": [], "index": {}}
            batches.append(cur)
        ids = []
        for p in packed:
            if p not in cur["index"]:
                cur["index"][p] = len(cur["verts"])
                cur["verts"].append(p)
            ids.append(cur["index"][p])
        if len(set(ids)) == 3:
            cur["tris"].append(ids)
    for b in batches:
        del b["index"]

    json.dump({"ship": ship, "charts": charts, "batches": batches},
              open(os.path.join(ROOT, "ships", ship + ".mesh.json"), "w"))
    print("%s: %d triangles, %d vertices in %d batches, %d textures (%s)"
          % (ship, sum(len(b["tris"]) for b in batches), sum(len(b["verts"]) for b in batches),
             len(batches), len(charts), ", ".join("%dx%d" % (c["w"], c["h"]) for c in charts)))


if __name__ == "__main__":
    main()
