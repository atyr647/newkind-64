#!/usr/bin/env python3
"""
Bake a texture for an original Elite ship from a detailed reference model.

The ship keeps its exact original geometry (shipdata.c / shipface.c). This
tool gives every face texture coordinates, then fills a small N64-sized
texture by looking up, for each texel, the nearest point on a detailed
reference model (for example one generated by Tripo) after squashing that
model into the original ship's bounding box.

  bake_ship_texture.py <ship> <reference.glb> <out_prefix> [points] [size]

Writes <out_prefix>.png (the texture, 16 colours) and <out_prefix>.uv.json
(texture coordinates, in texels, for every vertex of every face).

Needs: numpy, pillow, trimesh, scipy, rtree.
"""
import json
import math
import sys

import numpy as np
import trimesh
from PIL import Image

sys.path.insert(0, __file__.rsplit("/", 1)[0])
from ship_export import load_ship  # noqa: E402


def dominant_axis(normal):
    a = int(np.argmax(np.abs(normal)))
    return a, (1 if normal[a] >= 0 else -1)


def chart_axes(axis):
    """The two model axes a chart is laid out along, for a projection axis."""
    return {0: (2, 1), 1: (0, 2), 2: (0, 1)}[axis]


def load_reference(path):
    scene = trimesh.load(path, force="scene")
    meshes = [g for g in scene.dump() if isinstance(g, trimesh.Trimesh)]
    mesh = trimesh.util.concatenate(meshes) if len(meshes) > 1 else meshes[0]
    image = mesh.visual.material.baseColorTexture.convert("RGB")
    return mesh, np.asarray(mesh.visual.uv), np.asarray(image)


def sample(image, uv):
    h, w, _ = image.shape
    x = np.clip((uv[:, 0] % 1.0) * (w - 1), 0, w - 1).astype(int)
    y = np.clip((1.0 - (uv[:, 1] % 1.0)) * (h - 1), 0, h - 1).astype(int)
    return image[y, x].astype(float)


def orient_reference(mesh, uv, image, target_extent):
    """
    Work out which way round the reference model is, and return a function
    mapping points in original ship space into reference space.

    The reference is assumed to be y-up. Its forward axis is whichever of
    x or z has the redder end (the engines), and that end is the rear.
    """
    lo, hi = mesh.bounds
    centre = (lo + hi) / 2
    half = (hi - lo) / 2
    tri_centres = mesh.triangles_center
    tri_uv = uv[mesh.faces].mean(axis=1)
    colours = sample(image, tri_uv)
    redness = colours[:, 0] - (colours[:, 1] + colours[:, 2]) / 2

    best = None
    for axis in (0, 2):
        t = (tri_centres[:, axis] - centre[axis]) / half[axis]
        for sign in (1, -1):
            end = (t * sign) > 0.8
            score = redness[end].mean() if end.any() else -1e9
            if best is None or score > best[0]:
                best = (score, axis, sign)
    _, fwd_axis, rear_sign = best
    side_axis = 2 if fwd_axis == 0 else 0

    def to_reference(points):
        # original: x = right, y = up, z = forwards (nose at +z)
        p = np.asarray(points, dtype=float)
        n = (p - target_extent[0]) / (target_extent[1] - target_extent[0]) * 2 - 1
        out = np.zeros_like(p)
        out[:, side_axis] = centre[side_axis] + n[:, 0] * half[side_axis]
        out[:, 1] = centre[1] + n[:, 1] * half[1]
        out[:, fwd_axis] = centre[fwd_axis] - rear_sign * n[:, 2] * half[fwd_axis]
        return out

    return to_reference


def point_in_poly(px, py, poly):
    inside = np.zeros(px.shape, dtype=bool)
    n = len(poly)
    for i in range(n):
        x1, y1 = poly[i]
        x2, y2 = poly[(i + 1) % n]
        cond = ((y1 > py) != (y2 > py))
        with np.errstate(divide="ignore", invalid="ignore"):
            xi = (x2 - x1) * (py - y1) / (y2 - y1) + x1
        inside ^= cond & (px < xi)
    return inside


def main():
    ship, ref_path, prefix = sys.argv[1], sys.argv[2], sys.argv[3]
    point_name = sys.argv[4] if len(sys.argv) > 4 else ship + "_point"
    size = int(sys.argv[5]) if len(sys.argv) > 5 else 64

    points, faces = load_ship(ship + "_face", point_name)
    pts = np.array(points, dtype=float)
    solid = [(i, f) for i, f in enumerate(faces) if len(f[2]) >= 3]

    # --- charts: faces sharing a projection direction share a chart ---------
    charts = {}
    for i, (_, normal, vs) in solid:
        n = np.array(normal, dtype=float)
        if np.linalg.norm(n) < 1e-6:
            p = pts[vs]
            n = np.cross(p[1] - p[0], p[2] - p[0])
        charts.setdefault(dominant_axis(n), []).append(i)

    chart_info = {}
    for key, flist in charts.items():
        a, b = chart_axes(key[0])
        used = np.array([pts[v] for i in flist for v in faces[i][2]])
        chart_info[key] = dict(a=a, b=b, min=(used[:, a].min(), used[:, b].min()),
                               w=max(used[:, a].max() - used[:, a].min(), 1.0),
                               h=max(used[:, b].max() - used[:, b].min(), 1.0))

    # --- pack the charts on shelves, as large as will fit --------------------
    def pack(scale):
        x = y = shelf = 0
        placed = {}
        for key in sorted(chart_info, key=lambda k: -chart_info[k]["h"]):
            c = chart_info[key]
            w = int(math.ceil(c["w"] * scale)) + 2
            h = int(math.ceil(c["h"] * scale)) + 2
            if w > size:
                return None
            if x + w > size:
                x, y, shelf = 0, y + shelf, 0
            if y + h > size:
                return None
            placed[key] = (x + 1, y + 1)
            x += w
            shelf = max(shelf, h)
        return placed

    lo_s, hi_s = 0.01, 10.0
    for _ in range(40):
        mid = (lo_s + hi_s) / 2
        if pack(mid):
            lo_s = mid
        else:
            hi_s = mid
    scale = lo_s
    placed = pack(scale)

    def face_uv(i):
        _, normal, vs = faces[i]
        key = next(k for k, fl in charts.items() if i in fl)
        c = chart_info[key]
        ox, oy = placed[key]
        return [(ox + (pts[v][c["a"]] - c["min"][0]) * scale,
                 oy + (pts[v][c["b"]] - c["min"][1]) * scale) for v in vs], key

    # --- reference model ------------------------------------------------------
    ref, ref_uv, ref_img = load_reference(ref_path)
    extent = (pts.min(axis=0), pts.max(axis=0))
    to_reference = orient_reference(ref, ref_uv, ref_img, extent)

    tex = np.zeros((size, size, 3), dtype=float)
    covered = np.zeros((size, size), dtype=bool)
    yy, xx = np.mgrid[0:size, 0:size]
    cx, cy = xx + 0.5, yy + 0.5

    uv_out = {}
    for i, (_, normal, vs) in solid:
        uvs, key = face_uv(i)
        uv_out[str(i)] = [[round(u, 3), round(v, 3)] for u, v in uvs]
        c = chart_info[key]
        ox, oy = placed[key]

        # A slightly grown polygon so texels on the edges get filled too.
        centre = np.mean(uvs, axis=0)
        grown = [tuple(centre + (np.array(p) - centre) * 1.0 + np.sign(np.array(p) - centre) * 0.75) for p in uvs]
        mask = point_in_poly(cx, cy, grown) & ~covered
        if not mask.any():
            continue

        # Back from texel to a 3D point on the face's plane.
        n = np.array(normal, dtype=float)
        p0 = pts[vs[0]]
        if np.linalg.norm(n) < 1e-6:
            n = np.cross(pts[vs[1]] - p0, pts[vs[2]] - p0)
        a, b, k = c["a"], c["b"], key[0]
        pa = c["min"][0] + (cx[mask] - ox) / scale
        pb = c["min"][1] + (cy[mask] - oy) / scale
        pk = p0[k] - (n[a] * (pa - p0[a]) + n[b] * (pb - p0[b])) / n[k]
        p3 = np.zeros((mask.sum(), 3))
        p3[:, a], p3[:, b], p3[:, k] = pa, pb, pk
        p3 = np.clip(p3, extent[0], extent[1])

        closest, _, tri = trimesh.proximity.closest_point(ref, to_reference(p3))
        bary = trimesh.triangles.points_to_barycentric(ref.triangles[tri], closest)
        uv = (ref_uv[ref.faces[tri]] * bary[:, :, None]).sum(axis=1)
        tex[mask] = sample(ref_img, uv)
        covered |= mask

    # --- fill the gaps between charts with their nearest colour --------------
    from scipy import ndimage
    if covered.any() and not covered.all():
        idx = ndimage.distance_transform_edt(~covered, return_distances=False, return_indices=True)
        tex = tex[idx[0], idx[1]]

    img = Image.fromarray(np.clip(tex, 0, 255).astype(np.uint8), "RGB")
    img.save(prefix + ".full.png")
    img.quantize(16, method=Image.MEDIANCUT, dither=Image.NONE).save(prefix + ".png")
    json.dump({"ship": ship, "size": size, "faces": uv_out}, open(prefix + ".uv.json", "w"), indent=1)
    print("%s: %d faces, %d charts, %.3f texels per unit, %d%% of texture used"
          % (ship, len(solid), len(charts), scale, 100 * covered.mean()))


if __name__ == "__main__":
    main()
