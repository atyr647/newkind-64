#!/usr/bin/env python3
"""
Generate n64_shiptex.c from the converted ship models in ships/.

Each ships/<name>.mesh.json (written by convert_ship_model.py) becomes a
table of vertex batches; the ships/<name>_<n>.png textures are converted to
sprites by the Makefile. SHIP_TYPES says which game ship types use each model.
"""
import glob
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

SHIP_TYPES = {
    "cobra3": ["SHIP_COBRA3", "SHIP_COBRA3_LONE"],
}

out = ["/*",
       " * Elite - The New Kind.",
       " *",
       " * N64: replacement ship models for the Enhanced renderer.",
       " * Generated by tools/gen_ship_textures.py - do not edit by hand.",
       " */",
       "",
       '#include "shipdata.h"',
       '#include "n64_ships3d.h"',
       ""]
entries = []
for path in sorted(glob.glob(os.path.join(ROOT, "ships", "*.mesh.json"))):
    data = json.load(open(path))
    name = data["ship"]
    out.append("static const char *const %s_sprites[] = { %s };" % (
        name, ", ".join('"rom:/%s.sprite"' % c["file"] for c in data["charts"])))
    out.append("")
    for i, b in enumerate(data["batches"]):
        out.append("/* x, y, z, normal (x127), u, v (1/32 texel), smooth normal (x127) */")
        out.append("static const short %s_v%d[] = {" % (name, i))
        for v in b["verts"]:
            out.append("\t" + ", ".join("%d" % x for x in v) + ",")
        out.append("};")
        out.append("static const unsigned char %s_t%d[] = { %s };" % (
            name, i, ", ".join("%d" % x for t in b["tris"] for x in t)))
    out.append("")
    out.append("static const struct ship_mesh_batch %s_batches[] =" % name)
    out.append("{")
    for i, b in enumerate(data["batches"]):
        out.append("\t{%d, %d, %d, %s_v%d, %s_t%d}," % (b["chart"], len(b["verts"]), len(b["tris"]), name, i, name, i))
    out.append("};")
    out.append("")
    for t in SHIP_TYPES.get(name, []):
        entries.append("\t{%s, %d, %s_sprites, %d, %s_batches}," % (
            t, len(data["charts"]), name, len(data["batches"]), name))

out.append("const struct ship_mesh ship_meshes[] =")
out.append("{")
out += entries
out.append("\t{0, 0, 0, 0, 0}")
out.append("};")
open(os.path.join(ROOT, "n64_shiptex.c"), "w").write("\n".join(out) + "\n")
print("wrote n64_shiptex.c (%d ship types with new models)" % len(entries))
