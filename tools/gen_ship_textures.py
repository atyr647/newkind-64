#!/usr/bin/env python3
"""
Generate n64_shiptex.c from the baked ship textures in ships/.

Each ships/<name>.uv.json (written by bake_ship_texture.py) becomes a table
of texture coordinates; ships/<name>.png is converted to a sprite by the
Makefile. SHIP_TYPES says which game ship types use each texture.
"""
import glob
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

SHIP_TYPES = {
    "cobra3": ["SHIP_COBRA3", "SHIP_COBRA3_LONE"],
}

out = ["/*",
       " * Elite - The New Kind.",
       " *",
       " * N64: texture coordinates for the textured ships.",
       " * Generated by tools/gen_ship_textures.py - do not edit by hand.",
       " */",
       "",
       '#include "shipdata.h"',
       '#include "n64_ships3d.h"',
       ""]
entries = []
for path in sorted(glob.glob(os.path.join(ROOT, "ships", "*.uv.json"))):
    data = json.load(open(path))
    name = data["ship"]
    faces = data["faces"]
    count = max(int(k) for k in faces) + 1
    out.append("/* Per face: up to 8 (u, v) pairs, in 1/32 texel units. */")
    out.append("static const short %s_uv[%d][16] =" % (name, count))
    out.append("{")
    for i in range(count):
        row = []
        for u, v in faces.get(str(i), []):
            row += [int(round(u * 32)), int(round(v * 32))]
        row += [0] * (16 - len(row))
        out.append("\t{" + ", ".join("%d" % x for x in row) + "},")
    out.append("};")
    out.append("")
    for t in SHIP_TYPES.get(name, []):
        entries.append('\t{%s, "rom:/%s.sprite", %d, %s_uv},' % (t, name, count, name))

out.append("const struct ship_texture ship_textures[] =")
out.append("{")
out += entries
out.append("\t{0, 0, 0, 0}")
out.append("};")
open(os.path.join(ROOT, "n64_shiptex.c"), "w").write("\n".join(out) + "\n")
print("wrote n64_shiptex.c (%d textured ship types)" % len(entries))
